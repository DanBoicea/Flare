// Generates the demo seed SQL from data/airport/airport.json (task D01). Node built-ins only.
//
//   node scripts/seed/generate-seed.mjs
//
// Writes apps/flare-backend/src/main/resources/db/seed/R__demo_seed.sql. Flyway re-runs that file
// whenever its contents change, so regenerate it after editing airport.json and commit both.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const airport = JSON.parse(readFileSync(join(root, 'data/airport/airport.json'), 'utf8'));
const outFile = join(root, 'apps/flare-backend/src/main/resources/db/seed/R__demo_seed.sql');

if (airport.simulated !== true) {
  throw new Error('airport.json must say "simulated": true');
}

/** A SQL string literal. */
const q = (value) => `'${String(value).replaceAll("'", "''")}'`;

const lines = [];
const add = (...more) => lines.push(...more);

add(
  '-- SIMULATED DEMO DATA, not real airport data. Not the layout of Craiova International Airport.',
  '-- Generated by scripts/seed/generate-seed.mjs from data/airport/airport.json. Do not edit by hand.',
  '-- Loaded only by the local and demo profiles. Every statement is an upsert, so re-running is safe.',
  '',
  '-- ---------- Areas ----------',
);
for (const area of airport.areas) {
  add(
    `insert into flare.area (id, name_ro, name_en) values (${q(area.id)}, ${q(area.name.ro)}, ${q(area.name.en)})`,
    '    on conflict (id) do update set name_ro = excluded.name_ro, name_en = excluded.name_en;',
  );
}

add('', '-- ---------- Locations (matched by label) ----------');
for (const location of airport.locations) {
  add(
    'insert into flare.location (area_id, label, name_ro, name_en, criticality)',
    `    values (${q(location.area)}, ${q(location.label)}, ${q(location.name.ro)}, ${q(location.name.en)}, ${location.criticality})`,
    '    on conflict (label) do update set area_id = excluded.area_id, name_ro = excluded.name_ro,',
    '        name_en = excluded.name_en, criticality = excluded.criticality;',
  );
}

add('', '-- ---------- QR codes ----------');
for (const location of airport.locations) {
  add(
    'insert into flare.qr_code (id, location_id, status)',
    `    select ${q(location.qrCodeId)}, id, ${q(location.qrCodeStatus ?? 'ACTIVE')} from flare.location where label = ${q(location.label)}`,
    '    on conflict (id) do update set location_id = excluded.location_id, status = excluded.status;',
  );
}

add(
  '',
  '-- ---------- Staff, linked to Supabase Auth users by email ----------',
  '-- A user that doesn\'t exist in auth.users yet is skipped: the select returns no rows.',
  '-- Teams and roles are replaced, so the database always matches airport.json.',
);
for (const member of airport.staff) {
  const user = `select id from auth.users where email = ${q(member.email)}`;
  add(
    '',
    `-- ${member.email}`,
    'insert into flare.staff_member (id, display_name, active)',
    `    select id, ${q(member.displayName)}, true from auth.users where email = ${q(member.email)}`,
    '    on conflict (id) do update set display_name = excluded.display_name, active = true;',
    `delete from flare.staff_member_team where staff_member_id in (${user});`,
    `delete from flare.staff_member_role where staff_member_id in (${user});`,
  );
  for (const team of member.teams) {
    add(`insert into flare.staff_member_team (staff_member_id, team_id) select id, ${q(team)} from flare.staff_member where id in (${user});`);
  }
  for (const role of member.roles) {
    add(`insert into flare.staff_member_role (staff_member_id, role_id) select id, ${q(role)} from flare.staff_member where id in (${user});`);
  }
}

writeFileSync(outFile, lines.join('\n') + '\n');
console.log(`Wrote ${outFile}: ${airport.areas.length} Areas, ${airport.locations.length} Locations, ${airport.staff.length} staff members.`);
